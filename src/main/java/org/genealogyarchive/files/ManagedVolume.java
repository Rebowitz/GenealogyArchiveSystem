package org.genealogyarchive.files;

import org.genealogyarchive.platform.SafeFiles;

import java.io.IOException;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import java.util.Optional;
import java.nio.file.LinkOption;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.attribute.BasicFileAttributes;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Objects;
import java.util.UUID;

/**
 * An initialized Storage Volume whose marker has been verified for this archive (P2-D), and the
 * single place that turns a portable location inside it into a native path (BUILD-SPEC s.27).
 * <p>
 * Layout below the root:
 * <pre>
 *   .genealogy-archive-volume      identity marker
 *   originals/ab/cd/&lt;content-id&gt;    preservation originals (generation 1)
 *   originals/ab/cd/&lt;content-id&gt;.g2 a repaired generation
 *   quarantine/&lt;operation-id&gt;-...   objects set aside for a person to decide about; never auto-deleted
 * </pre>
 * Physical names derive only from identities generated by the archive (lower-case hex UUIDs), never
 * from user-supplied names, and are sharded on the UUID's random bits (PF-003). Every access checks
 * the directory chain without following links.
 */
public final class ManagedVolume {

    public static final String ORIGINALS = "originals";
    public static final String QUARANTINE = "quarantine";

    private final UUID volumeId;
    private final Path root;

    private ManagedVolume(UUID volumeId, Path root) {
        this.volumeId = volumeId;
        this.root = root;
    }

    /**
     * Opens the volume after verifying that it is configured, present and carries this archive's
     * marker for this volume.
     *
     * @throws VolumeUnavailableException with the precise reason otherwise
     */
    public static ManagedVolume open(VolumeRoots roots, UUID volumeId, UUID archiveId) {
        Path root = roots.rootOf(volumeId).orElseThrow(() ->
                new VolumeUnavailableException(volumeId, VolumeUnavailableException.Reason.NOT_CONFIGURED));
        if (!Files.isDirectory(root)) {
            throw new VolumeUnavailableException(volumeId, VolumeUnavailableException.Reason.ROOT_UNAVAILABLE);
        }
        VolumeMarker marker;
        try {
            marker = VolumeMarker.readFrom(root);
        } catch (NoSuchFileException e) {
            throw new VolumeUnavailableException(volumeId, VolumeUnavailableException.Reason.NOT_INITIALIZED);
        } catch (VolumeMarker.InvalidMarkerException e) {
            throw new VolumeUnavailableException(volumeId, VolumeUnavailableException.Reason.MARKER_INVALID);
        } catch (java.nio.file.AccessDeniedException e) {
            throw new VolumeUnavailableException(volumeId, VolumeUnavailableException.Reason.MARKER_ACCESS_DENIED);
        } catch (IOException e) {
            throw new VolumeUnavailableException(volumeId, VolumeUnavailableException.Reason.ROOT_UNAVAILABLE);
        }
        if (!marker.archiveId().equals(archiveId) || !marker.volumeId().equals(volumeId)) {
            throw new VolumeUnavailableException(volumeId, VolumeUnavailableException.Reason.MARKER_MISMATCH);
        }
        return new ManagedVolume(volumeId, root);
    }

    /**
     * Initializes an existing, empty-of-marker root directory: writes the marker (exclusive create)
     * and the managed sub-directories.
     */
    public static void initialize(Path root, UUID archiveId, UUID volumeId, Instant now) throws IOException {
        SafeFiles.requirePlainDirectory(root);
        new VolumeMarker(VolumeMarker.CURRENT_FORMAT, archiveId, volumeId, now).writeTo(root);
        SafeFiles.ensurePlainDirectory(root.resolve(ORIGINALS));
        SafeFiles.ensurePlainDirectory(root.resolve(QUARANTINE));
    }

    public UUID volumeId() {
        return volumeId;
    }

    public Path root() {
        return root;
    }

    /** Portable location of a content generation's preservation original. */
    public static PortableRelativePath originalPath(UUID contentId, int generation) {
        if (generation < 1) {
            throw new IllegalArgumentException("generation starts at 1");
        }
        String id = contentId.toString().toLowerCase(Locale.ROOT);
        String name = generation == 1 ? id : id + ".g" + generation;
        return PortableRelativePath.ofSegments(ORIGINALS, id.substring(32, 34), id.substring(34, 36), name);
    }

    /** Portable location for an object set aside by {@code operationId}. */
    public static PortableRelativePath quarantinePath(UUID operationId, String suffix) {
        Objects.requireNonNull(suffix, "suffix");
        if (!suffix.matches("[a-z0-9-]{1,40}")) {
            throw new IllegalArgumentException("quarantine suffix must be a short lower-case code");
        }
        return PortableRelativePath.ofSegments(QUARANTINE, operationId.toString().toLowerCase(Locale.ROOT) + "-" + suffix);
    }

    /**
     * Native path of an existing location after checking that every directory below the root is a
     * plain directory (no link, junction or reparse point).
     */
    public Path resolveExisting(PortableRelativePath path) throws IOException {
        Path target = path.toNative(root);
        SafeFiles.requirePlainDirectoryChain(root, target);
        return target;
    }

    /**
     * Native path of a location whose directories below the root all exist as plain directories, or
     * empty if one of them is missing (GAS-P2-007: a lost shard or {@code originals} directory means the
     * object is missing, not that the volume is unreadable). A link, junction, reparse point or
     * non-directory in the chain is refused with {@link SafeFiles.UnsafePathException}; a missing volume
     * root throws {@link NoSuchFileException} because then nothing below it can be judged.
     */
    public Optional<Path> locate(PortableRelativePath path) throws IOException {
        Path target = path.toNative(root);
        if (!Files.isDirectory(root)) {
            throw new NoSuchFileException(root.toString(), null, "volume root is not available");
        }
        Path relativeParent = root.relativize(target).getParent();
        Path current = root;
        if (relativeParent != null) {
            for (Path name : relativeParent) {
                current = current.resolve(name);
                if (!Files.exists(current, LinkOption.NOFOLLOW_LINKS)) {
                    return Optional.empty();
                }
                SafeFiles.requirePlainDirectory(current);
            }
        }
        SafeFiles.requirePlainDirectoryChain(root, target);
        return Optional.of(target);
    }

    /** Like {@link #resolveExisting}, creating any missing directories (each checked as plain). */
    public Path prepare(PortableRelativePath path) throws IOException {
        Path target = path.toNative(root);
        Path current = root;
        Path relativeParent = root.relativize(target).getParent();
        if (relativeParent != null) {
            for (Path name : relativeParent) {
                current = current.resolve(name);
                SafeFiles.ensurePlainDirectory(current);
            }
        }
        SafeFiles.requirePlainDirectoryChain(root, target);
        return target;
    }

    /** One object found below {@code originals/}. */
    public record Entry(PortableRelativePath path, Kind kind, long size) {
        public enum Kind { FILE, LINK_OR_REPARSE, OTHER }
    }

    /**
     * Lists everything below {@code originals/} without following links (for integrity checks).
     * Links and reparse points are reported, not entered.
     */
    public List<Entry> listOriginals() throws IOException {
        Path originals = root.resolve(ORIGINALS);
        List<Entry> entries = new ArrayList<>();
        if (!Files.exists(originals)) {
            return entries;
        }
        SafeFiles.requirePlainDirectory(originals);
        Files.walkFileTree(originals, new SimpleFileVisitor<>() {
            @Override
            public FileVisitResult preVisitDirectory(Path dir, BasicFileAttributes attrs) throws IOException {
                if (!dir.equals(originals) && SafeFiles.isLinkOrReparsePoint(dir)) {
                    entries.add(new Entry(PortableRelativePath.fromNative(root, dir), Entry.Kind.LINK_OR_REPARSE, 0));
                    return FileVisitResult.SKIP_SUBTREE;
                }
                return FileVisitResult.CONTINUE;
            }

            @Override
            public FileVisitResult visitFile(Path file, BasicFileAttributes attrs) throws IOException {
                Entry.Kind kind = SafeFiles.isLinkOrReparsePoint(file) ? Entry.Kind.LINK_OR_REPARSE
                        : attrs.isRegularFile() ? Entry.Kind.FILE : Entry.Kind.OTHER;
                entries.add(new Entry(PortableRelativePath.fromNative(root, file), kind, attrs.size()));
                return FileVisitResult.CONTINUE;
            }
        });
        return entries;
    }

    /** Why a volume cannot be used right now. */
    public static final class VolumeUnavailableException extends RuntimeException {

        public enum Reason {
            NOT_CONFIGURED("this installation has no root configured for it"),
            ROOT_UNAVAILABLE("its root directory is not available (disconnected, unmounted or inaccessible)"),
            NOT_INITIALIZED("it has not been initialized (no volume marker)"),
            MARKER_INVALID("its volume marker is unreadable or malformed"),
            MARKER_ACCESS_DENIED("this service is not permitted to read its volume marker (check the folder's permissions)"),
            MARKER_MISMATCH("its marker belongs to a different archive or volume");

            private final String explanation;

            Reason(String explanation) {
                this.explanation = explanation;
            }

            public String explanation() {
                return explanation;
            }
        }

        private final UUID volumeId;
        private final Reason reason;

        public VolumeUnavailableException(UUID volumeId, Reason reason) {
            super("Storage Volume " + volumeId + " cannot be used: " + reason.explanation());
            this.volumeId = volumeId;
            this.reason = reason;
        }

        public UUID volumeId() {
            return volumeId;
        }

        public Reason reason() {
            return reason;
        }
    }
}
